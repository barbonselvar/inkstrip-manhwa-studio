#!/usr/bin/env node
/**
 * Sustained stability / memory test of the desktop app.
 *
 *   node apps/desktop/test/stability-desktop.mjs --exe <exe> [--minutes 60] [--out <dir>]
 *
 * Builds a 20-panel chapter, then loops real work until the time is up: Images ⇄
 * Composition & FX (scrolling) ⇄ Text & Bubbles, Raster Studio (brush stroke + undo,
 * back), and Ctrl+S every 5 cycles. Every 30 s it samples the total working set of all
 * app processes and the studio's JS heap. Reports growth after warm-up, errors, crashes.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { waitShellStatus, windowPages } from "./window-pages.mjs";
import { stabilityOutcome } from "./stability-outcome.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..", "..");
const { _electron: electron } = await import(pathToFileURL(join(root, "node_modules", "playwright", "index.mjs")).href);
const arg = (n) => {
  const i = process.argv.indexOf(n);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const exe = arg("--exe");
const minutes = Number(arg("--minutes") ?? 60);
if (!exe || !Number.isFinite(minutes) || minutes <= 0)
  throw new Error("--exe and a finite, positive --minutes value are required");
const out = resolve(arg("--out") ?? join(tmpdir(), `inkstrip-stability-${Date.now()}`));
mkdirSync(join(out, "panels"), { recursive: true });

const app = await electron.launch({ executablePath: exe, env: { ...process.env, INKSTRIP_PROFILE_DIR: join(out, "profile") }, timeout: 60_000 });
await app.evaluate(({ session }) => session.defaultSession.enableNetworkEmulation({ offline: true }));
const { studio, shell } = await windowPages(app);
const errors = [];
let crashed = null;
studio.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
studio.on("console", (m) => m.type() === "error" && !/unsafe-eval/.test(m.text()) && errors.push(m.text()));
studio.on("crash", () => (crashed = "renderer crashed"));
app.process().once("exit", (code) => (crashed ??= `app exited (${code})`));
await studio.waitForSelector(".desktop-toasts", { state: "attached", timeout: 60_000 });

const samples = [];
const started = Date.now();
const sample = async (label) => {
  const m = await app.evaluate(({ app }) => {
    const all = app.getAppMetrics();
    return {
      workingSetMB: Math.round(all.reduce((s, p) => s + p.memory.workingSetSize, 0) / 1024),
      cpuPercent: all.reduce((s, p) => s + p.cpu.percentCPUUsage, 0),
      processes: all.length,
    };
  });
  const heapMB = await studio.evaluate(() => Math.round((performance.memory?.usedJSHeapSize ?? 0) / 1048576));
  samples.push({ minute: +((Date.now() - started) / 60000).toFixed(1), label, ...m, heapMB });
};

// 20 synthetic 1080×1600 panels generated by the renderer, written to disk.
const b64 = await studio.evaluate(async () => {
  const out = [];
  for (let k = 0; k < 20; k++) {
    const c = new OffscreenCanvas(1080, 1600), g = c.getContext("2d");
    const grad = g.createLinearGradient(0, 0, 1080, 1600);
    grad.addColorStop(0, `hsl(${k * 31} 50% 70%)`);
    grad.addColorStop(1, `hsl(${k * 31 + 150} 40% 25%)`);
    g.fillStyle = grad;
    g.fillRect(0, 0, 1080, 1600);
    g.fillStyle = "white";
    g.font = "bold 80px sans-serif";
    g.fillText(`PANEL ${k + 1}`, 60, 160);
    const bytes = new Uint8Array(await (await c.convertToBlob({ type: "image/jpeg", quality: 0.9 })).arrayBuffer());
    let bin = "";
    for (let j = 0; j < bytes.length; j += 0x8000) bin += String.fromCharCode(...bytes.subarray(j, j + 0x8000));
    out.push(btoa(bin));
  }
  return out;
});
const paths = b64.map((d, i) => {
  const p = join(out, "panels", `${String(i + 1).padStart(2, "0")}.jpg`);
  writeFileSync(p, Buffer.from(d, "base64"));
  return p;
});
await studio.getByRole("button", { name: "New project", exact: true }).click();
await studio.getByLabel("Project title").fill("Stability");
await studio.getByRole("button", { name: "Create chapter 1", exact: true }).click();
await studio.getByRole("button", { name: "Add images", exact: true }).waitFor({ timeout: 30_000 });
await studio.locator("input[type=file][multiple]").first().setInputFiles(paths);
await studio.getByRole("button", { name: "Display 20", exact: true }).waitFor({ timeout: 120_000 });
await app.evaluate(({ dialog }, p) => {
  dialog.showSaveDialog = async () => ({ canceled: false, filePath: p });
}, join(out, "stability.inkstrip"));
await studio.keyboard.press("Control+s");
await waitShellStatus(shell, /Saved · stability\.inkstrip/, 60_000);
await sample("start");

let cycles = 0;
let lastSample = Date.now();
const step = async (fn) => {
  try {
    await fn();
  } catch (error) {
    errors.push(`step: ${String(error.message ?? error).split("\n")[0]}`);
    await studio.keyboard.press("Escape").catch(() => {});
  }
};
while (Date.now() - started < minutes * 60_000 && !crashed) {
  cycles++;
  await step(async () => {
    await studio.getByRole("button", { name: "Composition & FX", exact: true }).click();
    await studio.locator("[data-composition=studio]").waitFor({ timeout: 60_000 });
    for (let k = 0; k < 12; k++) {
      await studio.mouse.move(900, 500);
      await studio.mouse.wheel(0, k < 6 ? 1600 : -1600);
      await studio.waitForTimeout(80);
    }
  });
  await step(async () => {
    await studio.getByRole("button", { name: "Text & Bubbles", exact: true }).click();
    await studio.locator("[data-composition=lettering]").waitFor({ timeout: 60_000 });
  });
  await step(async () => {
    await studio.getByRole("button", { name: "Images", exact: true }).click();
    await studio.getByRole("button", { name: "Open in Raster Studio", exact: true }).click();
    await studio.getByRole("dialog", { name: "Inkstrip Raster Studio", exact: true }).waitFor({ timeout: 60_000 });
    const board = await studio.locator(".pro-artboard").first().boundingBox();
    await studio.getByRole("button", { name: "Brush tool", exact: true }).click();
    await studio.mouse.move(board.x + board.width * 0.3, board.y + board.height * 0.5);
    await studio.mouse.down();
    await studio.mouse.move(board.x + board.width * 0.7, board.y + board.height * 0.5, { steps: 10 });
    await studio.mouse.up();
    await studio.getByRole("button", { name: "Pro undo", exact: true }).click();
    await studio.getByRole("button", { name: "Back to chapter from Pro Studio", exact: true }).click();
    await studio.getByRole("dialog", { name: "Inkstrip Raster Studio", exact: true }).waitFor({ state: "detached", timeout: 30_000 });
  });
  if (cycles % 5 === 0) await step(async () => {
    await studio.keyboard.press("Control+s");
    await waitShellStatus(shell, /Saved · stability\.inkstrip/, 60_000);
  });
  if (Date.now() - lastSample > 30_000) {
    lastSample = Date.now();
    await sample(`cycle ${cycles}`).catch((e) => errors.push(`sample: ${e.message}`));
    writeFileSync(join(out, "stability-progress.json"), JSON.stringify({ cycles, samples, errorCount: errors.length, errors: [...new Set(errors)] }, null, 1));
  }
}
if (!crashed) await sample("end").catch((error) => errors.push(`final sample: ${error.message}`));

const warm = samples.find((s) => s.minute >= 5) ?? samples[0];
const end = samples.at(-1);
const result = {
  exe,
  minutes,
  cycles,
  elapsedMs: Date.now() - started,
  crashed,
  errors: [...new Set(errors)].slice(0, 50),
  errorCount: errors.length,
  start: samples[0],
  afterWarmup: warm,
  end,
  peakWorkingSetMB: Math.max(...samples.map((s) => s.workingSetMB)),
  growthAfterWarmupMB: end && warm ? end.workingSetMB - warm.workingSetMB : null,
  heapGrowthAfterWarmupMB: end && warm ? end.heapMB - warm.heapMB : null,
  samples,
};
Object.assign(result, stabilityOutcome(result));
writeFileSync(join(out, "stability-results.json"), JSON.stringify(result, null, 2));
console.log(JSON.stringify({ ...result, samples: undefined }, null, 2));
await app.evaluate(({ app }) => app.exit(0)).catch(() => {});
process.exit(result.passed ? 0 : 1);
